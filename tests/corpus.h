static void corpus_fix1(uint8_t *c, unsigned n)
{
    c[2] = (uint8_t) n;
    c[3] = (uint8_t) (n >> 8);
}

static void corpus_fix(void)
{
    corpus_fix1(cfg_cm108, sizeof cfg_cm108);
    corpus_fix1(cfg_headset, sizeof cfg_headset);
    corpus_fix1(cfg_44k, sizeof cfg_44k);
    corpus_fix1(cfg_uac2, sizeof cfg_uac2);
    corpus_fix1(cfg_mic, sizeof cfg_mic);
}

